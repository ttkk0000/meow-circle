package mobile

import "time"

type Audience struct {
	Mode    string  `json:"mode"` // private, public, friends, selected, excluded
	UserIDs []int64 `json:"user_ids,omitempty"`
}

type Pet struct {
	AdoptionCycle     int64    `json:"adoption_cycle"`
	AdoptionOpened    bool     `json:"adoption_opened"`
	PlacementState    string   `json:"placement_state,omitempty"`
	Name              string   `json:"name"`
	Species           string   `json:"species"`
	Breed             string   `json:"breed,omitempty"`
	Birthday          string   `json:"birthday,omitempty"`
	Sex               string   `json:"sex,omitempty"`
	Bio               string   `json:"bio,omitempty"`
	Health            string   `json:"health,omitempty"`
	Missing           bool     `json:"missing"`
	Audience          Audience `json:"audience"`
	AdoptionAvailable bool     `json:"adoption_available"`
}

type Friend struct {
	RequesterID int64      `json:"requester_id"`
	RecipientID int64      `json:"recipient_id"`
	Reason      string     `json:"reason,omitempty"`
	AcceptedAt  *time.Time `json:"accepted_at,omitempty"`
	BlockedBy   int64      `json:"blocked_by,omitempty"`
}

type Entry struct {
	ContentOrigin string   `json:"content_origin,omitempty"` // set by the service after a manifest-bound declaration
	Title         string   `json:"title,omitempty"`
	Category      string   `json:"category,omitempty"`
	Tags          []string `json:"tags,omitempty"`
	PetID         int64    `json:"pet_id,omitempty"`
	Space         string   `json:"space"` // community, circle, diary
	Text          string   `json:"text"`
	Audience      Audience `json:"audience"`
}

type RichContent struct {
	Text      string `json:"text,omitempty"`
	StickerID string `json:"sticker_id,omitempty"`
}

type Comment struct {
	RichContent
	ReplyTo int64 `json:"reply_to,omitempty"`
}

type Case struct {
	LocationPrecision string    `json:"location_precision,omitempty"` // area: no public coordinate; approximate: coarse point
	Type              string    `json:"type"`                         // lost, found
	PetID             int64     `json:"pet_id,omitempty"`
	Title             string    `json:"title"`
	Species           string    `json:"species"`
	Description       string    `json:"description"`
	City              string    `json:"city"`
	Area              string    `json:"area"`
	Latitude          float64   `json:"latitude"` // coarse public centre
	Longitude         float64   `json:"longitude"`
	OccurredAt        time.Time `json:"occurred_at"`
	PrivateLocation   string    `json:"private_location,omitempty"`
	ClosureReason     string    `json:"closure_reason,omitempty"`
	MatchedClaimID    int64     `json:"matched_claim_id,omitempty"`
}

type Claim struct {
	PetName           string `json:"pet_name"`
	Evidence          string `json:"evidence"`
	OwnerConfirmed    bool   `json:"publisher_confirmed"`
	ClaimantConfirmed bool   `json:"claimant_confirmed"`
	Note              string `json:"note,omitempty"`
}

type Subscription struct {
	LocationPrecision string  `json:"location_precision,omitempty"` // city or approximate; empty preserves legacy point semantics
	City              string  `json:"city"`
	Latitude          float64 `json:"latitude"`
	Longitude         float64 `json:"longitude"`
	RadiusKM          float64 `json:"radius_km"`
	Frequency         string  `json:"frequency"`
	Enabled           bool    `json:"enabled"`
}

type AppointmentTerms struct {
	City          string              `json:"city"`
	Species       string              `json:"species"`
	Snapshot      *DisclosureSnapshot `json:"snapshot,omitempty"` // generated by the service, never trusted from a client
	StartsAt      time.Time           `json:"starts_at"`
	Place         string              `json:"place"`
	Reception     string              `json:"reception"`
	PetName       string              `json:"pet_name"`
	AmountCents   int64               `json:"amount_cents"`
	VisitFeeCents int64               `json:"visit_fee_cents"`
	RequiredFees  string              `json:"required_fees"`
	Payee         string              `json:"payee"`
}

type AppointmentVersion struct {
	Number        int64            `json:"number"`
	Terms         AppointmentTerms `json:"terms"`
	ProposedBy    int64            `json:"proposed_by"`
	Confirmations []int64          `json:"confirmations"`
	Status        string           `json:"status"`
	CreatedAt     time.Time        `json:"created_at"`
}

type Appointment struct {
	ContextKind      string               `json:"context_kind"`
	ContextID        int64                `json:"context_id"`
	PeerID           int64                `json:"peer_id"`
	EffectiveVersion int64                `json:"effective_version"`
	PendingVersion   int64                `json:"pending_version"`
	Versions         []AppointmentVersion `json:"versions"`
	Reason           string               `json:"reason,omitempty"`
}

type Adoption struct {
	AdoptionCycle         int64              `json:"adoption_cycle"`
	Contracts             []ContractRevision `json:"contracts"`
	EffectiveContract     int64              `json:"effective_contract"`
	ReturnPlans           []ReturnPlan       `json:"return_plans"`
	EffectiveReturn       int64              `json:"effective_return"`
	PetID                 int64              `json:"pet_id"`
	ApplicantID           int64              `json:"applicant_id"`
	PublisherID           int64              `json:"publisher_id"`
	Message               string             `json:"message"`
	Supplement            string             `json:"supplement,omitempty"`
	TrialTerms            string             `json:"trial_terms,omitempty"`
	TrialUntil            *time.Time         `json:"trial_until,omitempty"`
	TrialConfirmations    []int64            `json:"trial_confirmations"`
	HandoverConfirmations []int64            `json:"handover_confirmations"`
	CompletedAt           *time.Time         `json:"completed_at,omitempty"`
	Note                  string             `json:"note,omitempty"`
}

type CareUpdate struct {
	Text      string `json:"text"`
	NeedsHelp bool   `json:"needs_help"`
}

type Group struct {
	Name              string     `json:"name"`
	Notice            string     `json:"notice,omitempty"`
	Members           []int64    `json:"members"`
	Muted             []int64    `json:"muted"`
	PendingTransferTo int64      `json:"pending_transfer_to,omitempty"`
	TransferExpiresAt *time.Time `json:"transfer_expires_at,omitempty"`
}

type GroupMessage struct{ RichContent }

type Conversation struct {
	RequesterID int64 `json:"requester_id"`
	RecipientID int64 `json:"recipient_id"`
}
type Message struct{ RichContent }
type Lead struct {
	Text string `json:"text"`
}

type Invitation struct {
	Scope       string    `json:"scope"` // group_member, adoption_editor, caretaker
	TargetID    int64     `json:"target_id"`
	RecipientID int64     `json:"recipient_id"`
	ExpiresAt   time.Time `json:"expires_at"`
}

type Preference struct {
	DirectMessages bool   `json:"direct_messages"`
	Groups         bool   `json:"groups"`
	Applications   bool   `json:"applications"`
	Interactions   bool   `json:"interactions"`
	Frequency      string `json:"frequency"`
	PushPermission bool   `json:"push_permission"`
}

type ExpressionState struct {
	Favorites []string `json:"favorites"`
	Recent    []string `json:"recent"`
}

type Draft struct {
	ContextKind string   `json:"context_kind"`
	ContextID   int64    `json:"context_id,omitempty"`
	PetID       int64    `json:"pet_id,omitempty"`
	Text        string   `json:"text"`
	Audience    Audience `json:"audience"`
	Cursor      int      `json:"cursor"`
}

type Notification struct {
	PushReceipts []PushAcceptance `json:"push_receipts,omitempty"`
	DeliverAfter *time.Time       `json:"deliver_after,omitempty"`
	CaseIDs      []int64          `json:"case_ids,omitempty"`
	Category     string           `json:"category"`
	Text         string           `json:"text"`
	TargetKind   Kind             `json:"target_kind"`
	TargetID     int64            `json:"target_id"`
	Read         bool             `json:"read"`
	PushState    string           `json:"push_state"` // queued, suppressed, accepted, delivered
}

type MediaFile struct {
	UploadLeaseUntil *time.Time `json:"upload_lease_until,omitempty"`
	KnownAI          bool       `json:"known_ai"`
	SourceLabel      string     `json:"source_label,omitempty"` // recognized AIGC label only; never raw EXIF or location
	Scope            string     `json:"scope"`                  // private evidence never flows into a public publication
	Filename         string     `json:"filename"`               // persisted; stripped from every HTTP projection
	MIME             string     `json:"mime"`
	Size             int64      `json:"size"`
	SHA256           string     `json:"sha256"`
	Width            int        `json:"width"`
	Height           int        `json:"height"`
}

type Review struct {
	Check             string     `json:"check,omitempty"`
	TargetVersion     int64      `json:"target_version,omitempty"`
	ReviewedAt        *time.Time `json:"reviewed_at,omitempty"`
	ValidUntil        *time.Time `json:"valid_until,omitempty"`
	Type              string     `json:"type"` // report, verification, appeal, recovery, support
	TargetKind        Kind       `json:"target_kind"`
	TargetID          int64      `json:"target_id"`
	Reason            string     `json:"reason"`
	Summary           string     `json:"summary,omitempty"`
	EvidenceExpiresAt *time.Time `json:"evidence_expires_at,omitempty"`
	AppealOf          int64      `json:"appeal_of,omitempty"`
	InternalNote      string     `json:"internal_note,omitempty"` // staff only; stripped from owner projections
}

type Feedback struct {
	AppointmentID int64             `json:"appointment_id"`
	Version       int64             `json:"appointment_version"`
	Items         map[string]string `json:"items"` // identity/reception/place/fees: match, mismatch, unknown
	Note          string            `json:"note,omitempty"`
}
