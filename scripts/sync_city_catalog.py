"""Derive bundled city catalogs; default is read-only. No builds, network or app execution."""
from pathlib import Path
import json
import sys

root = Path(__file__).resolve().parents[1]
source = root / 'internal/region/mainland-cities.json'
catalog = json.loads(source.read_text(encoding='utf-8'))
provinces, cities = catalog['provinces'], catalog['cities']
assert len(provinces) == 31
assert len({c['code'] for c in cities}) == len(cities)
assert len({c['value'] for c in cities}) == len(cities)
assert all(c['provinceCode'] in {p['code'] for p in provinces} for c in cities)
assert all(0 < c['latitude'] < 54 and 73 < c['longitude'] < 136 for c in cities)
assert not any(c['provinceCode'] in ('71', '81', '82', '91') for c in cities)
assert {'北京市', '上海市', '重庆市', '武汉市', '仙桃市', '石河子市', '白杨市', '恩施土家族苗族自治州', '锡林郭勒盟', '大兴安岭地区', '神农架林区'} <= {c['name'] for c in cities}

blocks = []
for province in provinces:
    rows = []
    for city in cities:
        if city['provinceCode'] == province['code']:
            rows.append('|'.join(str(city[k]) for k in ('code', 'provinceCode', 'name', 'value', 'parentName', 'pinyin', 'latitude', 'longitude', 'alias')))
    blocks.append('    """' + '\n'.join(rows) + '"""')
kotlin = '''// Generated by scripts/sync_city_catalog.py from internal/region/mainland-cities.json.
// Source: xiangyuecn/AreaCity-JsSpider-StatsGov, MIT; see internal/region/README.md.
package com.ttkk0000.meowcircle.client

internal val mainlandCityRows: List<String> = listOf(
''' + ',\n'.join(blocks) + '\n)\n'
province_rows = ',\n'.join('    MainlandProvince(' + json.dumps(p['code']) + ', ' + json.dumps(p['name'], ensure_ascii=False) + ')' for p in provinces)
kotlin += '\nval mainlandProvinces: List<MainlandProvince> = listOf(\n' + province_rows + '\n)\n'
outputs = {
    root / 'kmp/shared/src/commonMain/kotlin/com/ttkk0000/meowcircle/client/MainlandCityData.kt': kotlin,
    root / 'web-client/src/core/mainland-cities.json': json.dumps(catalog, ensure_ascii=False, indent=2) + '\n',
    root / 'web-client/public/assets/mainland-cities-LICENSE.txt': (source.parent / 'LICENSE').read_text(encoding='utf-8'),
    root / 'kmp/clientUi/src/commonMain/composeResources/files/mainland-cities-LICENSE.txt': (source.parent / 'LICENSE').read_text(encoding='utf-8'),
}
for path, content in outputs.items():
    if '--write' in sys.argv:
        path.write_text(content, encoding='utf-8', newline='\n')
    else:
        assert path.read_text(encoding='utf-8') == content, f'Catalog out of sync: {path}'
print(f'City catalog: {len(provinces)} provinces, {len(cities)} selectable cities/regions; derived files synchronized.')
